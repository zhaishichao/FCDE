import re
import pandas as pd

# ==========================================
# 1. 你的原始 LaTeX 表格行（可放很多行）
#    每行一个字符串
# ==========================================
latex_lines = [
    r'D1 & 79.57(5.25e-2)$+$ & 79.94(4.76e-2)$+$ & 80.40(5.10e-2)$+$ & 79.67(5.25e-2)$+$ & 81.27(5.94e-2)$+$ & 81.31(5.53e-2)$\approx$ & \hl{81.72(5.34e-2)} \\',

    r'D2 & \hl{88.91(6.72e-3)$-$} & 88.49(6.38e-3)$+$ & 88.49(7.32e-3)$+$ & 88.50(7.37e-3)$+$ & 87.25(8.02e-3)$+$ & 86.83(7.81e-3)$+$ & 88.78(6.81e-3) \\'
]

# ==========================================
# 2. 表头（你自己指定）
#    第一列必须是数据集名称
# ==========================================
columns = [
    "Dataset",
    "RAW",
    "ROS",
    "SMOTE",
    "SMOTEN",
    "Borderline-1",
    "Borderline-2",
    "GP-SMOTE"
]


# ==========================================
# 3. 提取函数
#    只提取：
#      - 数据集名（D1）
#      - 均值（79.57）
# ==========================================
def extract_means(line):
    # 去掉行尾 \\
    line = line.replace(r"\\", "").strip()

    # 按 &
    parts = [x.strip() for x in line.split("&")]

    dataset = parts[0]

    values = []

    for item in parts[1:]:
        # 去掉 \hl{}
        item = item.replace(r"\hl{", "").replace("}", "")

        # 提取开头均值（数字）
        m = re.search(r'(\d+\.\d+)', item)
        if m:
            values.append(float(m.group(1)))

    return [dataset] + values


# ==========================================
# 4. 批量处理
# ==========================================
rows = []

for line in latex_lines:
    rows.append(extract_means(line))

# ==========================================
# 5. 转 DataFrame
# ==========================================
df = pd.DataFrame(rows, columns=columns)

# ==========================================
# 6. 保存 CSV
# ==========================================
df.to_csv("latex_table_means.csv", index=False)

print(df)